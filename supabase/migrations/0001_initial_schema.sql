-- Public booking is intentionally the only unauthenticated write path.
-- It returns a one-time opaque token; the token hash is never exposed.
create or replace function public.create_public_booking(
  p_patient_name text, p_phone text, p_clinic_id bigint, p_service_id bigint,
  p_visit_date date, p_appointment_time time, p_age text default '',
  p_address text default '', p_national_id text default '', p_source text default 'public'
) returns jsonb language plpgsql security definer set search_path=public
as $$
declare c public.clinics; s public.clinic_services; b public.bookings; token text; used_count integer; max_count integer; booking_ref text;
begin
  select * into c from public.clinics where id=p_clinic_id and active for update;
  if not found then raise exception 'clinic_unavailable'; end if;
  select * into s from public.clinic_services where id=p_service_id and clinic_id=p_clinic_id and active and not direct_only;
  if not found then raise exception 'service_unavailable'; end if;
  if p_visit_date < current_date then raise exception 'past_date'; end if;
  if exists(select 1 from public.clinic_closures where clinic_id=c.id and closure_date=p_visit_date) then raise exception 'clinic_closed'; end if;
  if position(','||extract(dow from p_visit_date)::text||',' in ','||c.work_days||',')=0 then raise exception 'not_working_day'; end if;
  select count(*) into used_count from public.bookings where clinic_id=c.id and visit_date=p_visit_date and status not in ('Cancelled','NoShow');
  max_count=least(c.daily_limit,nullif(s.daily_limit,0));
  if max_count is null then max_count=c.daily_limit; end if;
  if used_count >= max_count then raise exception 'capacity_reached'; end if;
  if exists(select 1 from public.bookings where clinic_id=c.id and visit_date=p_visit_date and appointment_time=p_appointment_time and status not in ('Cancelled','NoShow')) then raise exception 'appointment_conflict'; end if;
  token=encode(gen_random_bytes(24),'hex'); booking_ref='B'||to_char(clock_timestamp(),'YYMMDDHH24MISS')||upper(substr(encode(gen_random_bytes(3),'hex'),1,6));
  insert into public.bookings(booking_no,public_token_hash,patient_name,age,address,phone,national_id,clinic_id,service_id,visit_date,appointment_time,service_type,status,source,instructions_snapshot,documents_snapshot)
  values(booking_ref,digest(token,'sha256'),trim(p_patient_name),coalesce(p_age,''),coalesce(p_address,''),trim(p_phone),coalesce(p_national_id,''),c.id,s.id,p_visit_date,p_appointment_time,s.name,case when c.direct_booking then 'Confirmed' else 'Pending' end,p_source,c.instructions,c.documents) returning * into b;
  return jsonb_build_object('booking_no',b.booking_no,'public_token',token,'status',b.status,'id',b.id);
end; $$;

create or replace function public.lookup_public_booking(p_booking_no text, p_public_token text)
returns jsonb language plpgsql security definer set search_path=public
as $$ declare b public.bookings; begin
  select * into b from public.bookings where booking_no=p_booking_no and public_token_hash=digest(p_public_token,'sha256');
  if not found then raise exception 'booking_not_found'; end if;
  return jsonb_build_object('booking_no',b.booking_no,'patient_name',b.patient_name,'clinic_id',b.clinic_id,'service_type',b.service_type,'visit_date',b.visit_date,'appointment_time',b.appointment_time,'status',b.status,'created_at',b.created_at);
end; $$;

